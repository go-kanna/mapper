package gen_test

import (
	"slices"
	"strings"
	"testing"

	"github.com/go-kanna/internal/pkgtest"

	"github.com/go-kanna/mapper/internal/gen"
)

func TestDecls(t *testing.T) {
	t.Parallel()

	found, diags := gen.Decls(pkgtest.Load(t, map[string]string{
		"types.go": `package test

type Employee struct {
	ID       string
	FullName string
}

type Wire struct {
	Id, Name string
	Revision int32
}
`,
		"mapper.go": `package test

//kanna:mapper
type _ interface {
	// ToWire converts an employee for the API.
	//
	//kanna:map Revision=- Name=FullName
	ToWire(e Employee) *Wire
	FromWire(*Wire) (Employee, error)
}

// The functions of both interfaces go into one file.
//
//kanna:mapper
type more interface {
	copyEmployee(_ Employee) Employee
}

type unmarked interface {
	Ignored(Employee) Wire
}
`,
		// An earlier run's output is not read, even if it carries the
		// directive.
		"mapper_gen.go": `// Code generated by kanna-mapper. DO NOT EDIT.

package test

//kanna:mapper
type _ interface {
	Stale(Employee) Wire
}
`,
	}))

	want := []string{
		"ToWire(e test.Employee) *test.Wire\n" +
			"  map: Revision=- (excluded), Name=FullName\n" +
			"  doc: ToWire converts an employee for the API.",
		"FromWire(src *test.Wire) (test.Employee, error)",
		"copyEmployee(src test.Employee) test.Employee",
	}
	if !slices.Equal(found, want) {
		t.Errorf("decls =\n%s\nwant\n%s", strings.Join(found, "\n"), strings.Join(want, "\n"))
	}
	if len(diags) > 0 {
		t.Errorf("diagnostics = %q, want none", diags)
	}
}

func TestDecls_Diagnostics(t *testing.T) {
	t.Parallel()

	// Every case uses these, after its own declarations.
	const pair = "\ntype E struct{ Name string }\n\ntype W struct{ Name string }\n"

	tests := []struct {
		name string
		src  string
		want string
	}{
		{
			name: "not an interface",
			src:  "//kanna:mapper\ntype Employee struct{ Name string }\n",
			want: "test.go:4:6: error: //kanna:mapper marks an interface; Employee is not one",
		},
		{
			name: "an alias",
			src:  "//kanna:mapper\ntype A = interface{ F(E) W }\n",
			want: "test.go:4:6: error: //kanna:mapper marks an interface declaration, not an alias",
		},
		{
			name: "generic",
			src:  "//kanna:mapper\ntype M[T any] interface{ F(T) W }\n",
			want: "test.go:4:6: error: generic interface M is not supported",
		},
		{
			name: "arguments",
			src:  "//kanna:mapper strict\ntype _ interface{ F(E) W }\n",
			want: `test.go:3:1: error: //kanna:mapper takes no arguments, got "strict"`,
		},
		{
			name: "misspelled",
			src:  "//kanna:mappr\ntype _ interface{ F(E) W }\n",
			want: `did you mean "//kanna:mapper"?`,
		},
		{
			name: "//kanna:map on the interface",
			src:  "//kanna:mapper\n//kanna:map Name=-\ntype _ interface{ F(E) W }\n",
			want: "test.go:4:1: error: //kanna:map goes above a method of the interface, not the interface",
		},
		{
			name: "no methods",
			src:  "//kanna:mapper\ntype _ interface{}\n",
			want: "test.go:4:6: warning: the interface has no methods, so it declares nothing to write",
		},
		{
			name: "embedding",
			src:  "type Base interface{ F(E) W }\n\n//kanna:mapper\ntype _ interface {\n\tBase\n}\n",
			want: "test.go:7:2: error: an interface marked //kanna:mapper cannot embed Base; declare its methods in it",
		},
		{
			// A method may be called init, but a function so named takes nothing.
			name: "init",
			src:  "//kanna:mapper\ntype _ interface {\n\tinit(E) W\n}\n",
			want: "test.go:5:2: error: init cannot be the name of a generated function",
		},
		{
			name: "two parameters",
			src:  "//kanna:mapper\ntype _ interface {\n\tF(E, int) W\n}\n",
			want: "test.go:5:2: error: F has to take one parameter, the source",
		},
		{
			name: "no parameter",
			src:  "//kanna:mapper\ntype _ interface {\n\tF() W\n}\n",
			want: "test.go:5:2: error: F has to take one parameter, the source",
		},
		{
			name: "variadic",
			src:  "//kanna:mapper\ntype _ interface {\n\tF(...E) W\n}\n",
			want: "test.go:5:2: error: F has to take one parameter, the source",
		},
		{
			name: "no result",
			src:  "//kanna:mapper\ntype _ interface {\n\tF(E)\n}\n",
			want: "test.go:5:2: error: F has to return the destination, or the destination and an error",
		},
		{
			name: "a second result that is not an error",
			src:  "//kanna:mapper\ntype _ interface {\n\tF(E) (W, bool)\n}\n",
			want: "test.go:5:2: error: F has to return the destination, or the destination and an error",
		},
		{
			name: "a source that is not a struct",
			src:  "//kanna:mapper\ntype _ interface {\n\tF(int) W\n}\n",
			want: "test.go:5:2: error: F: the source, int, is not a struct or a pointer to one",
		},
		{
			name: "a pointer to a pointer",
			src:  "//kanna:mapper\ntype _ interface {\n\tF(**E) W\n}\n",
			want: "test.go:5:2: error: F: the source, **test.E, is not a struct or a pointer to one",
		},
		{
			name: "a destination that is a slice",
			src:  "//kanna:mapper\ntype _ interface {\n\tF(E) []W\n}\n",
			want: "test.go:5:2: error: F: the destination, []test.W, is not a struct or a pointer to one",
		},
		{
			name: "a generic struct",
			src:  "//kanna:mapper\ntype _ interface {\n\tF(Box[int]) W\n}\n\ntype Box[T any] struct{ V T }\n",
			want: "test.go:5:2: error: F: the source, test.Box[int], is generic, which is not supported",
		},
		{
			name: "no exported fields",
			src:  "//kanna:mapper\ntype _ interface {\n\tF(E) Hidden\n}\n\ntype Hidden struct{ name string }\n",
			want: "test.go:5:2: error: F: the destination, test.Hidden, has no exported fields to map",
		},
		{
			name: "protobuf's Opaque API",
			src: "//kanna:mapper\ntype _ interface {\n\tF(E) *Opaque\n}\n\ntype Opaque struct{ name string }\n\n" +
				"func (o *Opaque) GetName() string { return o.name }\n",
			want: "test.go:5:2: error: F: the destination, *test.Opaque, has no exported fields to map\n" +
				"  types generated with protobuf's Opaque API are not supported",
		},
		{
			name: "//kanna:map without =",
			src:  "//kanna:mapper\ntype _ interface {\n\t//kanna:map Revision\n\tF(E) W\n}\n",
			want: `test.go:5:2: error: //kanna:map: "Revision" is not Field=Source or Field=-`,
		},
		{
			name: "//kanna:map with a bad field",
			src:  "//kanna:mapper\ntype _ interface {\n\t//kanna:map 9x=-\n\tF(E) W\n}\n",
			want: `test.go:5:2: error: //kanna:map: "9x" is not a field name`,
		},
		{
			name: "//kanna:map with a bad source",
			src:  "//kanna:mapper\ntype _ interface {\n\t//kanna:map Name=9x\n\tF(E) W\n}\n",
			want: `test.go:5:2: error: //kanna:map: "9x" is not a field name`,
		},
		{
			name: "//kanna:map naming a field twice",
			src:  "//kanna:mapper\ntype _ interface {\n\t//kanna:map Name=- Name=Title\n\tF(E) W\n}\n",
			want: "test.go:5:2: error: //kanna:map: Name appears twice",
		},
		{
			name: "//kanna:map saying nothing",
			src:  "//kanna:mapper\ntype _ interface {\n\t//kanna:map\n\tF(E) W\n}\n",
			want: "test.go:5:2: error: //kanna:map needs at least one Field=Source or Field=-",
		},
		{
			name: "a name declared by two interfaces",
			src:  "//kanna:mapper\ntype _ interface{ F(E) W }\n\n//kanna:mapper\ntype _ interface{ F(W) E }\n",
			want: "test.go:7:19: error: F is declared again; the first is at test.go:4:19",
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			_, diags := gen.Decls(pkgtest.Load(t, map[string]string{"test.go": "package test\n\n" + tt.src + pair}))
			if !slices.ContainsFunc(diags, func(d string) bool { return strings.Contains(d, tt.want) }) {
				t.Errorf("diagnostics = %q, want one containing %q", diags, tt.want)
			}
		})
	}
}
