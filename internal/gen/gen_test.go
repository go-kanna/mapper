// TestMain loads every module the tests write outside any workspace. A
// GOWORK pinned by the Makefile or the environment would otherwise put them
// outside the modules it lists, which the go command refuses to load.
func TestMain(m *testing.M) {
	// Before any test runs: t.Setenv would rule out t.Parallel.
	if err := os.Setenv("GOWORK", "off"); err != nil {
		panic(err)
	}
	os.Exit(m.Run())
}

// writeModule writes files into a fresh module, example.com/app, and returns
// its directory. The generated code imports nothing of this module, so the
// module needs no requirements.
func writeModule(t *testing.T, files map[string]string) string {
	t.Helper()

	dir := t.TempDir()
	files["go.mod"] = "module example.com/app\n\ngo 1.26.0\n"
	for name, content := range files {
		path := filepath.Join(dir, filepath.FromSlash(name))
		if err := os.MkdirAll(filepath.Dir(path), 0o750); err != nil {
			t.Fatal(err)
		}
		writeFile(t, path, content)
	}
	return dir
}

// run runs kanna-mapper in dir and returns its exit code, stdout, and stderr.
func run(t *testing.T, dir string, args ...string) (int, string, string) {
	t.Helper()

	var stdout, stderr bytes.Buffer
	code := gen.Command().Exec(cli.Env{Out: &stdout, Err: &stderr, Dir: dir}, args)
	return code, stdout.String(), stderr.String()
}

func writeFile(t *testing.T, path, content string) {
	t.Helper()

	if err := os.WriteFile(path, []byte(content), 0o600); err != nil {
		t.Fatal(err)
	}
}

func readFile(t *testing.T, path string) string {
	t.Helper()

	b, err := os.ReadFile(path) //nolint:gosec // a file of the test's own module
	if err != nil {
		t.Fatalf("read %s: %v", path, err)
	}
	return string(b)
}

// compiles reports whether the packages of dir load without errors.
func compiles(t *testing.T, dir string) {
	t.Helper()

	set, err := packages.Load([]string{"./..."}, packages.Config{Dir: dir})
	if err != nil || len(set.Diags) > 0 {
		t.Errorf("generated code does not load: %v %v", err, set.Diags)
	}
}

const typesSrc = `package app

import "net/netip"

type Employee struct {
	ID   netip.Addr
	Name string
	Home Address
}

type Address struct{ City string }

type EmployeePB struct {
	Id   string
	Name string
	Home *AddressPB
}

type AddressPB struct{ City string }
`

const mapperSrc = `package app

import "net/netip"

//kanna:mapper
type _ interface {
	ToPB(Employee) *EmployeePB
	FromPB(*EmployeePB) (Employee, error)
}

//kanna:convert
var _ = []any{
	netip.ParseAddr,
	netip.Addr.String,
}
`

func TestCommand_Generates(t *testing.T) {
	t.Parallel()

	dir := writeModule(t, map[string]string{"types.go": typesSrc, "mapper.go": mapperSrc})

	code, stdout, stderr := run(t, dir)
	if code != cli.ExitOK || stdout != "" || stderr != "" {
		t.Fatalf("run = %d, stdout %q, stderr %q; want success in silence", code, stdout, stderr)
	}
	got := readFile(t, filepath.Join(dir, "mapper_gen.go"))
	for _, want := range []string{
		"// Code generated by kanna-mapper. DO NOT EDIT.",
		"func ToPB(src Employee) *EmployeePB {",
		"func FromPB(src *EmployeePB) (Employee, error) {",
		"v, err := netip.ParseAddr(src.Id)",
		"func addressToAddressPB(src Address) *AddressPB {",
	} {
		if !strings.Contains(got, want) {
			t.Errorf("mapper_gen.go does not contain %q:\n%s", want, got)
		}
	}
	compiles(t, dir)

	// Generating again changes nothing, which -check confirms.
	if code, _, stderr := run(t, dir, "-check"); code != cli.ExitOK {
		t.Errorf("run -check = %d, stderr %q; want the output up to date", code, stderr)
	}
}

// A list another package declares is read from that package, which is loaded
// for it.
func TestCommand_SharedList(t *testing.T) {
	t.Parallel()

	dir := writeModule(t, map[string]string{
		"types.go": typesSrc,
		"convert/convert.go": `package convert

import "net/netip"

// Defaults is what every package of the app converts alike.
//
//kanna:convert
var Defaults = []any{
	netip.ParseAddr,
	netip.Addr.String,
}
`,
		"mapper.go": `package app

import "example.com/app/convert"

//kanna:mapper
type _ interface {
	ToPB(Employee) *EmployeePB
	FromPB(*EmployeePB) (Employee, error)
}

//kanna:convert
var _ = []any{convert.Defaults}
`,
	})

	// With no package named, the run still targets the current directory
	// alone, though it loads convert too.
	if code, stdout, stderr := run(t, dir); code != cli.ExitOK || stdout != "" || stderr != "" {
		t.Fatalf("run = %d, stdout %q, stderr %q; want success in silence", code, stdout, stderr)
	}
	if got := readFile(t, filepath.Join(dir, "mapper_gen.go")); !strings.Contains(got, "netip.ParseAddr(src.Id)") {
		t.Errorf("mapper_gen.go does not call the shared conversion:\n%s", got)
	}
	if _, err := os.Stat(filepath.Join(dir, "convert", "mapper_gen.go")); !os.IsNotExist(err) {
		t.Errorf("convert/mapper_gen.go exists, or cannot be checked: %v", err)
	}
	compiles(t, dir)
}

func TestCommand_RemovesWhatNoInterfaceDeclares(t *testing.T) {
	t.Parallel()

	dir := writeModule(t, map[string]string{"types.go": typesSrc, "mapper.go": mapperSrc})
	if code, _, stderr := run(t, dir); code != cli.ExitOK {
		t.Fatalf("run = %d, stderr %q", code, stderr)
	}

	// The last interface loses the directive.
	writeFile(t, filepath.Join(dir, "mapper.go"), strings.Replace(mapperSrc, "//kanna:mapper\n", "", 1))
	code, _, stderr := run(t, dir)
	if code != cli.ExitOK || !strings.Contains(stderr, "warning: no interface is marked //kanna:mapper in .") {
		t.Errorf("run = %d, stderr %q; want success with a warning", code, stderr)
	}
	if _, err := os.Stat(filepath.Join(dir, "mapper_gen.go")); !os.IsNotExist(err) {
		t.Errorf("mapper_gen.go is left, or cannot be checked: %v", err)
	}
}

// A line that only looks like a directive is warned about and otherwise
// ignored: the function is still generated, so the file stays even when it
// declares nothing else.
func TestCommand_KeepsOutputOnADirectiveWarning(t *testing.T) {
	t.Parallel()

	const src = "package app\n\nimport \"net/netip\"\n\n//kanna:mapper\ntype _ interface {\n" +
		"\tToPB(Employee) *EmployeePB\n}\n\n//kanna:convert\nvar _ = []any{netip.Addr.String}\n"

	tests := []struct{ name, line string }{
		{name: "spaced", line: "// kanna:map Id=-"},
		{name: "misspelled", line: "//kanna:mapp Id=-"},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			dir := writeModule(t, map[string]string{"types.go": typesSrc, "mapper.go": src})
			if code, _, stderr := run(t, dir); code != cli.ExitOK {
				t.Fatalf("run = %d, stderr %q", code, stderr)
			}

			writeFile(t, filepath.Join(dir, "mapper.go"), strings.Replace(src, "\tToPB(", "\t"+tt.line+"\n\tToPB(", 1))
			code, _, stderr := run(t, dir)
			if code != cli.ExitOK || !strings.Contains(stderr, "is not recognized as a directive") {
				t.Errorf("run = %d, stderr %q; want success with a warning", code, stderr)
			}
			got := readFile(t, filepath.Join(dir, "mapper_gen.go"))
			if !strings.Contains(got, "func ToPB(src Employee) *EmployeePB {") {
				t.Errorf("mapper_gen.go does not declare ToPB:\n%s", got)
			}
		})
	}
}

func TestCommand_ReportsWhatCannotBeMapped(t *testing.T) {
	t.Parallel()

	dir := writeModule(t, map[string]string{
		"types.go": typesSrc,
		"mapper.go": `package app

//kanna:mapper
type _ interface {
	ToPB(Employee) *EmployeePB
}
`,
	})

	code, _, stderr := run(t, dir)
	want := "./mapper.go:5:2: error: ToPB: cannot map app.Employee.ID (netip.Addr) to app.EmployeePB.Id (string)\n" +
		"  add a func(netip.Addr) string to a //kanna:convert list\n"
	if code != cli.ExitFailure || stderr != want {
		t.Errorf("run = %d, stderr\n%s\nwant\n%s", code, stderr, want)
	}
	if _, err := os.Stat(filepath.Join(dir, "mapper_gen.go")); !os.IsNotExist(err) {
		t.Errorf("mapper_gen.go is written, or cannot be checked: %v", err)
	}
}

// An earlier run's output that no longer compiles is set aside so the package
// can be read and the output written again.
func TestCommand_RegeneratesStaleOutput(t *testing.T) {
	t.Parallel()

	dir := writeModule(t, map[string]string{
		"types.go":  typesSrc,
		"mapper.go": mapperSrc,
		"mapper_gen.go": "// Code generated by kanna-mapper. DO NOT EDIT.\n\npackage app\n\n" +
			"func ToPB(src Employee) *EmployeePB { return &EmployeePB{Id: src.Gone} }\n",
	})

	if code, _, stderr := run(t, dir); code != cli.ExitOK || stderr != "" {
		t.Fatalf("run = %d, stderr %q; want success", code, stderr)
	}
	compiles(t, dir)
}

// A package that does not compile stops the run, and an earlier run's output
// set aside for it is pointed out.
func TestCommand_ReportsLoadErrors(t *testing.T) {
	t.Parallel()

	dir := writeModule(t, map[string]string{
		"types.go":  typesSrc,
		"mapper.go": mapperSrc,
		"use.go":    "package app\n\nvar _ = Old\n",
		"mapper_gen.go": "// Code generated by kanna-mapper. DO NOT EDIT.\n\npackage app\n\n" +
			"func Old(src Gone) {}\n",
	})

	code, _, stderr := run(t, dir)
	for _, want := range []string{
		"./use.go:3:9: error: undefined: Old",
		"./mapper_gen.go: warning: set aside because it no longer compiles;" +
			" it is regenerated once the errors above are fixed",
	} {
		if !strings.Contains(stderr, want) {
			t.Errorf("stderr does not contain %q:\n%s", want, stderr)
		}
	}
	if code != cli.ExitFailure {
		t.Errorf("run = %d, want %d", code, cli.ExitFailure)
	}
}
