// TestMain loads every module the tests write outside any workspace. A
// GOWORK pinned by the Makefile or the environment would otherwise put them
// outside the modules it lists, which the go command refuses to load.
func TestMain(m *testing.M) {
	// Before any test runs: t.Setenv would rule out t.Parallel.
	if err := os.Setenv("GOWORK", "off"); err != nil {
		panic(err)
	}
	os.Exit(m.Run())
}

// writeModule writes files into a fresh module, example.com/app, and returns
// its directory. The generated code imports nothing of this module, so the
// module needs no requirements.
func writeModule(t *testing.T, files map[string]string) string {
	t.Helper()

	dir := t.TempDir()
	files["go.mod"] = "module example.com/app\n\ngo 1.26.0\n"
	for name, content := range files {
		path := filepath.Join(dir, filepath.FromSlash(name))
		if err := os.MkdirAll(filepath.Dir(path), 0o750); err != nil {
			t.Fatal(err)
		}
		writeFile(t, path, content)
	}
	return dir
}

// run runs kanna-mapper in dir and returns its exit code, stdout, and stderr.
func run(t *testing.T, dir string, args ...string) (int, string, string) {
	t.Helper()

	var stdout, stderr bytes.Buffer
	code := gen.Command().Exec(cli.Env{Out: &stdout, Err: &stderr, Dir: dir}, args)
	return code, stdout.String(), stderr.String()
}

func writeFile(t *testing.T, path, content string) {
	t.Helper()

	if err := os.WriteFile(path, []byte(content), 0o600); err != nil {
		t.Fatal(err)
	}
}

func readFile(t *testing.T, path string) string {
	t.Helper()

	b, err := os.ReadFile(path) //nolint:gosec // a file of the test's own module
	if err != nil {
		t.Fatalf("read %s: %v", path, err)
	}
	return string(b)
}

// compiles reports whether the packages of dir load without errors.
func compiles(t *testing.T, dir string) {
	t.Helper()

	set, err := packages.Load([]string{"./..."}, packages.Config{Dir: dir})
	if err != nil || len(set.Diags) > 0 {
		t.Errorf("generated code does not load: %v %v", err, set.Diags)
	}
}

const typesSrc = `package app

import "net/netip"

type Employee struct {
	ID   netip.Addr
	Name string
	Home Address
}

type Address struct{ City string }

type EmployeePB struct {
	Id   string
	Name string
	Home *AddressPB
}

type AddressPB struct{ City string }
`

const mapperSrc = `package app

import "net/netip"

//kanna:mapper
type _ interface {
	ToPB(Employee) *EmployeePB
	FromPB(*EmployeePB) (Employee, error)
}

//kanna:converter
var _ = []any{
	netip.ParseAddr,
	netip.Addr.String,
}
`

func TestCommand_Generates(t *testing.T) {
	t.Parallel()

	dir := writeModule(t, map[string]string{"types.go": typesSrc, "mapper.go": mapperSrc})

	code, stdout, stderr := run(t, dir)
	if code != cli.ExitOK || stdout != "" || stderr != "" {
		t.Fatalf("run = %d, stdout %q, stderr %q; want success in silence", code, stdout, stderr)
	}
	got := readFile(t, filepath.Join(dir, "mapper_gen.go"))
	for _, want := range []string{
		"// Code generated by kanna-mapper. DO NOT EDIT.",
		"func ToPB(src Employee) *EmployeePB {",
		"func FromPB(src *EmployeePB) (Employee, error) {",
		"v, err := netip.ParseAddr(src.Id)",
		"func addressToAddressPB(src Address) *AddressPB {",
	} {
		if !strings.Contains(got, want) {
			t.Errorf("mapper_gen.go does not contain %q:\n%s", want, got)
		}
	}
	compiles(t, dir)

	// Generating again changes nothing, which -check confirms.
	if code, _, stderr := run(t, dir, "-check"); code != cli.ExitOK {
		t.Errorf("run -check = %d, stderr %q; want the output up to date", code, stderr)
	}
}

// A list another package declares is read from that package, which is loaded
// for it.
func TestCommand_SharedList(t *testing.T) {
	t.Parallel()

	dir := writeModule(t, map[string]string{
		"types.go": typesSrc,
		"convert/convert.go": `package convert

import "net/netip"

// Defaults is what every package of the app converts alike.
//
//kanna:converter
var Defaults = []any{
	netip.ParseAddr,
	netip.Addr.String,
}
`,
		"mapper.go": `package app

import "example.com/app/convert"

//kanna:mapper
type _ interface {
	ToPB(Employee) *EmployeePB
	FromPB(*EmployeePB) (Employee, error)
}

//kanna:converter
var _ = []any{convert.Defaults}
`,
	})

	// With no package named, the run still targets the current directory
	// alone, though it loads convert too.
	if code, stdout, stderr := run(t, dir); code != cli.ExitOK || stdout != "" || stderr != "" {
		t.Fatalf("run = %d, stdout %q, stderr %q; want success in silence", code, stdout, stderr)
	}
	if got := readFile(t, filepath.Join(dir, "mapper_gen.go")); !strings.Contains(got, "netip.ParseAddr(src.Id)") {
		t.Errorf("mapper_gen.go does not call the shared conversion:\n%s", got)
	}
	if _, err := os.Stat(filepath.Join(dir, "convert", "mapper_gen.go")); !os.IsNotExist(err) {
		t.Errorf("convert/mapper_gen.go exists, or cannot be checked: %v", err)
	}
	compiles(t, dir)
}

// An enum or a value type seen only through another package is made by its
// constructor, which its package is loaded for.
func TestCommand_LoadsThePackageOfAnEnumOrAValueType(t *testing.T) {
	t.Parallel()

	dir := writeModule(t, map[string]string{
		"domain/domain.go": `package domain

import "errors"

type Status string

const StatusActive Status = "active"

func NewStatus(v string) (Status, error) {
	if Status(v) != StatusActive {
		return "", errors.New("status")
	}
	return StatusActive, nil
}

type Nickname struct{ v string }

func NewNickname(v string) (Nickname, error) {
	if v == "" {
		return Nickname{}, errors.New("nickname")
	}
	return Nickname{v: v}, nil
}

func (n Nickname) String() string { return n.v }
`,
		"model/model.go": `package model

import "example.com/app/domain"

type Employee struct {
	Status   domain.Status
	Nickname domain.Nickname
}
`,
		"mapper.go": `package app

import "example.com/app/model"

type EmployeePB struct{ Status, Nickname string }

//kanna:mapper
type _ interface {
	FromPB(EmployeePB) (model.Employee, error)
}
`,
	})

	if code, stdout, stderr := run(t, dir); code != cli.ExitOK || stdout != "" || stderr != "" {
		t.Fatalf("run = %d, stdout %q, stderr %q; want success in silence", code, stdout, stderr)
	}
	got := readFile(t, filepath.Join(dir, "mapper_gen.go"))
	for _, want := range []string{"domain.NewStatus(src.Status)", "domain.NewNickname(src.Nickname)"} {
		if !strings.Contains(got, want) {
			t.Errorf("mapper_gen.go does not contain %q:\n%s", want, got)
		}
	}
	compiles(t, dir)
}

// The variants of a sum type and the arms of a oneof are taken file by file in
// name order, whichever file go/packages parses first, so that the output stays
// the same from one run to the next.
func TestGenerate_VariantsInFileOrder(t *testing.T) {
	t.Parallel()

	files := map[string]string{"mapper.go": `package app

type Payment interface{ isPayment() }

type S struct{ Payment Payment }

type isD_Payment interface{ isD_Payment() }

type D struct{ Payment isD_Payment }

//kanna:mapper
type _ interface {
	F(S) D
	G(D) (S, error)
}
`}
	want := make([]string, 0, 20)
	for i := range 10 {
		v := fmt.Sprintf("V%d", i)
		files[strings.ToLower(v)+".go"] = fmt.Sprintf("package app\n\ntype %[1]s struct{ N int }\n\n"+
			"func (%[1]s) isPayment() {}\n\ntype %[1]sPB struct{ N int }\n\ntype D_%[1]s struct{ %[1]s *%[1]sPB }\n\n"+
			"func (*D_%[1]s) isD_Payment() {}\n", v)
		want = append(want, "case "+v+":", "case *D_"+v+":")
	}
	dir := writeModule(t, files)

	for range 5 {
		set, err := packages.Load([]string{"."}, packages.Config{Dir: dir, TypesInfo: true})
		if err != nil || len(set.Diags) > 0 {
			t.Fatalf("load: %v %v", err, set.Diags)
		}
		changes, diags := gen.Generate(set)
		if len(changes) != 1 || len(diags) > 0 {
			t.Fatalf("generate = %d changes, diagnostics %q; want one, and none", len(changes), diags)
		}
		out := string(changes[0].Data)
		for _, pair := range [][2]string{{"case V", "case V"}, {"case *D_V", "case *D_V"}} {
			last := -1
			for _, w := range want {
				if !strings.HasPrefix(w, pair[0]) {
					continue
				}
				i := strings.Index(out, w)
				if i < last {
					t.Fatalf("%s comes before what an earlier file declares:\n%s", w, out)
				}
				last = i
			}
		}
	}
}

func TestCommand_RemovesWhatNoInterfaceDeclares(t *testing.T) {
	t.Parallel()

	dir := writeModule(t, map[string]string{"types.go": typesSrc, "mapper.go": mapperSrc})
	if code, _, stderr := run(t, dir); code != cli.ExitOK {
		t.Fatalf("run = %d, stderr %q", code, stderr)
	}

	// The last interface loses the directive.
	writeFile(t, filepath.Join(dir, "mapper.go"), strings.Replace(mapperSrc, "//kanna:mapper\n", "", 1))
	code, _, stderr := run(t, dir)
	if want := "warning: no interface is marked //kanna:mapper in example.com/app\n"; code != cli.ExitOK ||
		!strings.Contains(stderr, want) {
		t.Errorf("run = %d, stderr %q; want success with a warning", code, stderr)
	}
	if _, err := os.Stat(filepath.Join(dir, "mapper_gen.go")); !os.IsNotExist(err) {
		t.Errorf("mapper_gen.go is left, or cannot be checked: %v", err)
	}
}

// The warning names packages by import path: go generate ./... runs each in
// its own directory, where "." names them all alike.
func TestCommand_WarnsWhenNothingIsMarked(t *testing.T) {
	t.Parallel()

	const listsHint = "  a package holding only //kanna:converter lists needs no //go:generate line;" +
		" the packages naming its lists read them\n"

	files := func() map[string]string {
		return map[string]string{
			"model/model.go": "package model\n\ntype Employee struct{ Name string }\n",
			"docs/README.md": "# Docs\n",
			"convert/convert.go": "package convert\n\nimport \"strconv\"\n\n" +
				"//kanna:converter\nvar Defaults = []any{strconv.Itoa}\n",
		}
	}
	tests := []struct {
		name, in string
		args     []string
		want     string
	}{
		{
			name: "a package",
			in:   "model",
			want: "warning: no interface is marked //kanna:mapper in example.com/app/model\n",
		},
		{
			name: "a package holding only lists",
			in:   "convert",
			want: "warning: no interface is marked //kanna:mapper in example.com/app/convert\n" + listsHint,
		},
		{
			name: "several packages",
			args: []string{"./..."},
			want: "warning: no interface is marked //kanna:mapper in example.com/app/convert, example.com/app/model\n" +
				listsHint,
		},
		{
			name: "no package",
			args: []string{"./docs/..."},
			want: "warning: no interface is marked //kanna:mapper in ./docs/...\n",
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			dir := writeModule(t, files())
			code, stdout, stderr := run(t, filepath.Join(dir, tt.in), tt.args...)
			if code != cli.ExitOK || stdout != "" || stderr != tt.want {
				t.Errorf("run = %d, stdout %q, stderr\n%s\nwant\n%s", code, stdout, stderr, tt.want)
			}
		})
	}
}

// A line that only looks like a directive is warned about and otherwise
// ignored: the function is still generated, so the file stays even when it
// declares nothing else.
func TestCommand_KeepsOutputOnADirectiveWarning(t *testing.T) {
	t.Parallel()

	const src = "package app\n\nimport \"net/netip\"\n\n//kanna:mapper\ntype _ interface {\n" +
		"\tToPB(Employee) *EmployeePB\n}\n\n//kanna:converter\nvar _ = []any{netip.Addr.String}\n"

	tests := []struct{ name, line, want string }{
		{name: "spaced", line: "// kanna:map Id=-", want: "is not recognized as a directive"},
		{name: "misspelled", line: "//kanna:mapp Id=-", want: "is not recognized as a directive"},
		// A blank line keeps it from the method's doc comment.
		{name: "loose", line: "//kanna:map Id=-\n", want: "//kanna:map is not attached to a declaration"},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			dir := writeModule(t, map[string]string{"types.go": typesSrc, "mapper.go": src})
			if code, _, stderr := run(t, dir); code != cli.ExitOK {
				t.Fatalf("run = %d, stderr %q", code, stderr)
			}

			writeFile(t, filepath.Join(dir, "mapper.go"), strings.Replace(src, "\tToPB(", "\t"+tt.line+"\n\tToPB(", 1))
			code, _, stderr := run(t, dir)
			if code != cli.ExitOK || !strings.Contains(stderr, tt.want) {
				t.Errorf("run = %d, stderr %q; want success with a warning", code, stderr)
			}
			got := readFile(t, filepath.Join(dir, "mapper_gen.go"))
			if !strings.Contains(got, "func ToPB(src Employee) *EmployeePB {") {
				t.Errorf("mapper_gen.go does not declare ToPB:\n%s", got)
			}
		})
	}
}

